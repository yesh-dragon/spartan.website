import { Link } from "react-router-dom";
import type { AlertRecord } from "@agent-guard/shared";
import { ArrowRight, CheckCircle2, ShieldAlert } from "lucide-react";
import { SeverityPill } from "../shared/SeverityPill";
import { formatRelativeTime } from "../../lib/format";
import { Button } from "../shared/Button";

export function RecentAlerts({ alerts }: { alerts: AlertRecord[] }) {
  return (
    <section className="rounded-xl border border-hairline bg-surface p-5 shadow-panel">
      <div className="flex flex-wrap items-center justify-between gap-2 border-b border-hairline pb-4">
        <div className="flex items-center gap-2.5">
          <div className="flex h-8 w-8 items-center justify-center rounded-lg border border-hairline bg-surface-2 text-danger">
            <ShieldAlert className="h-4 w-4" aria-hidden="true" />
          </div>
          <div>
            <h2 className="font-display text-base font-semibold text-ink">
              Recent Explainable Alerts
            </h2>
            <p className="text-xs text-ink-muted">
              Plain-language security explanations generated by Agent Guard
            </p>
          </div>
        </div>

        <Link
          to="/alerts"
          className="inline-flex items-center gap-1 font-mono text-xs text-accent hover:underline"
        >
          View all
          <ArrowRight className="h-3.5 w-3.5" aria-hidden="true" />
        </Link>
      </div>

      {alerts.length === 0 ? (
        <div className="py-10 text-center">
          <p className="text-sm text-ink-muted">
            No alerts triggered yet. Open the Playground and test the urgent invoice email.
          </p>
          <div className="mt-4">
            <Link to="/playground">
              <Button size="sm" variant="primary" icon={<ArrowRight className="h-3.5 w-3.5" />}>
                Open Playground
              </Button>
            </Link>
          </div>
        </div>
      ) : (
        <ul className="divide-y divide-hairline">
          {alerts.map((alert) => (
            <li key={alert.id} className="py-3.5 first:pt-4 last:pb-1">
              <div className="flex flex-wrap items-center justify-between gap-2">
                <div className="flex items-center gap-2">
                  <SeverityPill severity={alert.severity} />
                  <h3 className="font-display text-sm font-semibold text-ink">{alert.title}</h3>
                </div>
                <div className="flex items-center gap-2 font-mono text-[11px] text-ink-dim">
                  {alert.acknowledged && (
                    <span className="inline-flex items-center gap-1 text-accent">
                      <CheckCircle2 className="h-3 w-3" aria-hidden="true" />
                      Ack
                    </span>
                  )}
                  <span>{formatRelativeTime(alert.created_at)}</span>
                </div>
              </div>
              <p className="mt-1.5 text-xs leading-relaxed text-ink-muted">{alert.explanation}</p>
            </li>
          ))}
        </ul>
      )}
    </section>
  );
}

